// UI strings are written in Vietnamese and double as their own keys: `tr('Hôm nay')`. Other languages map a key
// to its text; a missing entry falls back to the Vietnamese. `{name}` placeholders fill from `vars`.
// The language is set once at startup (root _layout, from prefs) and a change reloads the app, so nothing here
// re-renders. Never call tr() at module level: constants keep the Vietnamese key and translate where rendered.
// No imports: logic.check runs the libs that use this in plain node.

export type Lang = 'vi' | 'en';
export const LANGS: { value: Lang; label: string }[] = [
  { value: 'vi', label: 'Tiếng Việt' },
  { value: 'en', label: 'English' },
];

let lang: Lang = 'vi';
export const setLang = (l: string | null) => { lang = l === 'en' ? 'en' : 'vi'; };
export const getLang = () => lang;

export function tr(key: string, vars?: Record<string, string | number>) {
  const s = (lang === 'en' && en[key]) || key;
  return vars ? s.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m)) : s;
}

