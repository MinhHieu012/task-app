// Writes src/environments/supabase.ts (gitignored) from the environment before serve/build/test.
// Only the public URL and the publishable/anon key go into the bundle; a secret key aborts the build.
// Sources, first hit wins: process env (Vercel), apps/web/.env.local, the repo root .env.local.
// Names: SUPABASE_URL / SUPABASE_KEY, or the Expo names the project already uses (EXPO_PUBLIC_SUPABASE_*).
import fs from 'node:fs';

const files = ['.env.local', '../../.env.local'].filter((f) => fs.existsSync(f));
const fromFiles = Object.assign({}, ...files.reverse().map((f) => Object.fromEntries(
  fs.readFileSync(f, 'utf8').split(/\r?\n/).map((l) => l.match(/^\s*([\w.]+)\s*=\s*(.*?)\s*$/)).filter(Boolean).map((m) => [m[1], m[2].replace(/^(['"])(.*)\1$/, '$2')]),
)));
const get = (...names) => names.map((n) => process.env[n] ?? fromFiles[n]).find(Boolean);

const url = get('SUPABASE_URL', 'EXPO_PUBLIC_SUPABASE_URL');
const key = get('SUPABASE_KEY', 'SUPABASE_ANON_KEY', 'EXPO_PUBLIC_SUPABASE_KEY');
if (!url || !key) {
  console.error('env.mjs: set SUPABASE_URL and SUPABASE_KEY (or EXPO_PUBLIC_SUPABASE_URL/KEY) in the environment or .env.local');
  process.exit(1);
}
const role = (() => { try { return JSON.parse(Buffer.from(key.split('.')[1], 'base64url')).role; } catch { return null; } })();
if (key.startsWith('sb_secret_') || role === 'service_role') {
  console.error('env.mjs: refusing to ship a secret/service_role key in the web bundle; use the publishable (anon) key');
  process.exit(1);
}
new URL(url); // throws on a malformed URL

fs.writeFileSync('src/environments/supabase.ts', `// Generated by scripts/env.mjs. Do not edit or commit.\nexport const supabaseEnv = ${JSON.stringify({ url, key }, null, 2)};\n`);
console.log(`env.mjs: Supabase ${new URL(url).host}`);
